"""The state outline for the app header and the website: Pennsylvania (the Erie notch, the Delaware River edge), simplified from the
Census county outlines and normalized to a unit box.
Writes PennsylvaniaEats/Design/StateOutline.swift and playbook/state-outline.json (the website's generator reads the JSON).
Usage: .venv/bin/python scripts/make-outline.py"""
import os, json
from shapely.geometry import shape
from shapely.ops import unary_union

ROOT = os.path.join(os.path.dirname(__file__), "..")
feats = json.load(open(f"{ROOT}/data/pa/pa_counties.geojson"))["features"]
state = unary_union([shape(f["geometry"]) for f in feats]).buffer(0.004).buffer(-0.004)
poly = max(getattr(state, "geoms", [state]), key=lambda p: p.area)
minx, miny, maxx, maxy = poly.bounds
k = 0.755                                        # longitude shrinks by cos(41°)
w, h = (maxx - minx) * k, (maxy - miny)
q = poly.simplify(0.012, preserve_topology=True)
ring = [[round((x - minx) * k / w, 4), round(1 - (y - miny) / h, 4)] for x, y in q.exterior.coords]
out = {"aspect": round(w / h, 4), "outline": ring}
json.dump(out, open(f"{ROOT}/playbook/state-outline.json", "w"))
pts = "[" + ", ".join(f"({x}, {y})" for x, y in ring) + "]"
# the same outline in degrees, a little finer, for the app's "outside Pennsylvania" check (lat, lon)
g = poly.simplify(0.005, preserve_topology=True)
geo = "[" + ", ".join(f"({round(y, 4)}, {round(x, 4)})" for x, y in g.exterior.coords) + "]"
swift = f'''import SwiftUI

// Generated by scripts/make-outline.py from the Census county outlines (public domain). Don't edit by hand.

/// Pennsylvania's outline in a unit box (x right, y down): the one Pennsylvania element in the header (no keystone logo, no team marks).
enum StateOutline {{
    static let aspect: CGFloat = {out["aspect"]}
    static let outline: [(CGFloat, CGFloat)] = {pts}
    /// (latitude, longitude), for "is this point in Pennsylvania" (Pullman sits inside Idaho's box; boxes lie)
    static let geo: [(Double, Double)] = {geo}

    static func contains(latitude y: Double, longitude x: Double) -> Bool {{
        var inside = false
        var j = geo.count - 1
        for i in 0..<geo.count {{
            let (yi, xi) = geo[i], (yj, xj) = geo[j]
            if (yi > y) != (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi {{ inside.toggle() }}
            j = i
        }}
        return inside
    }}
}}

struct StateShape: Shape {{
    func path(in r: CGRect) -> Path {{
        // fit the unit box into r, keeping the state's proportions, aligned left
        let h = min(r.height, r.width / StateOutline.aspect), w = h * StateOutline.aspect
        var p = Path()
        guard let first = StateOutline.outline.first else {{ return p }}
        p.move(to: CGPoint(x: r.minX + first.0 * w, y: r.minY + first.1 * h))
        for pt in StateOutline.outline.dropFirst() {{ p.addLine(to: CGPoint(x: r.minX + pt.0 * w, y: r.minY + pt.1 * h)) }}
        p.closeSubpath()
        return p
    }}
}}
'''
open(f"{ROOT}/PennsylvaniaEats/Design/StateOutline.swift", "w").write(swift)
print("aspect", out["aspect"], "| points:", len(ring), "| geo points:", len(g.exterior.coords))
